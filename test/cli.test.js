import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";

import { VALID_ENV } from "../src/samples.js";
import { parseDotenv } from "../src/dotenv.js";

const run = (args) => execFileSync(process.execPath, ["scripts/cli.mjs", ...args], { encoding: "utf8" });

test("check accepts a valid environment and redacts secrets", () => {
  const output = run(["check", "--schema", "examples/env.schema.json", "--env", "examples/checkout.env"]);
  assert.match(output, /Environment is valid\./);
  assert.match(output, /ok\s+PORT/);
  assert.match(output, /sk••/);
  const apiKey = parseDotenv(VALID_ENV).values.API_KEY;
  assert.ok(!output.includes(apiKey), "CLI output leaked the API key");
});

test("check fails with an aggregated report for a broken environment", () => {
  assert.throws(
    () => run(["check", "--schema", "examples/env.schema.json", "--env", "examples/broken.env"]),
    (error) => {
      const output = String(error.stdout || "") + String(error.stderr || "");
      assert.match(output, /fail\s+PORT/);
      assert.match(output, /fail\s+API_KEY/);
      assert.match(output, /8 problems found/);
      assert.equal(error.status, 1);
      return true;
    },
  );
});

test("check --json never includes typed values", () => {
  const output = run(["check", "--schema", "examples/env.schema.json", "--env", "examples/checkout.env", "--json"]);
  const report = JSON.parse(output);
  assert.equal(report.ok, true);
  assert.equal(report.values, undefined);
  assert.equal(report.preview.PORT, "8080");
  assert.ok(!output.includes(parseDotenv(VALID_ENV).values.API_KEY));
});

test("type prints a TypeScript interface", () => {
  const output = run(["type", "--schema", "examples/env.schema.json"]);
  assert.match(output, /export interface Env \{/);
  assert.match(output, /PORT: number;/);
});

test("example prints a .env.example with defaults", () => {
  const output = run(["example", "--schema", "examples/env.schema.json"]);
  assert.match(output, /# Generated by EnvSafe/);
  assert.match(output, /PORT=3000/);
  assert.match(output, /API_KEY=\n/);
});

test("custom schema paths are reported when missing", () => {
  assert.throws(
    () => run(["check", "--schema", "nope.json", "--env", "examples/checkout.env"]),
    (error) => {
      assert.equal(error.status, 2);
      assert.match(String(error.stderr), /cannot read schema/);
      return true;
    },
  );
});
